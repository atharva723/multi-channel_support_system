"""Pydantic schemas for the triage API.

Typed request/response contracts shared between n8n (producer) and the Expo
client (consumer). ``SupportIngestPayload`` is the normalized shape n8n POSTs to
``/support/triage``; ``EscalationTicket`` is what the API returns and the mobile
dashboard renders.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class SupportIngestPayload(BaseModel):
    """Raw, normalized support message handed off from n8n to FastAPI."""

    channel: Literal["slack", "discord", "email"] = Field(
        ..., description="Source medium: slack, discord, or email"
    )
    channel_id: str = Field(
        ..., description="Internal channel or thread reference"
    )
    message_id: str = Field(
        ..., description="Unique message ID generated by the source platform"
    )
    author_name: str = Field(..., description="Sender's display name")
    author_contact: Optional[str] = Field(
        None, description="Email address or user handle"
    )
    content: str = Field(..., description="The raw support request string")
    timestamp: datetime = Field(default_factory=_utcnow)
    external_ref: Optional[str] = Field(
        None,
        description=(
            "Inbound routing key identifying the connected account this message "
            "belongs to (mailbox address / Discord guild id / Slack team id). "
            "Used to resolve the tenant when the caller is not authenticated."
        ),
    )


class EscalationTicket(BaseModel):
    """A triaged ticket as returned by the API / rendered on the dashboard."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    channel: str
    message_id: str
    author_name: str
    content: str
    criticality_score: float
    urgency_score: float
    ai_draft_reply: Optional[str] = None
    status: Literal["PENDING", "APPROVED", "MODIFIED", "DISMISSED"] = "PENDING"
    created_at: datetime


class TriageDecision(str, Enum):
    """Routing outcome of the triage engine for an ingested message."""

    ESCALATED = "ESCALATED"  # P(C=1|M) >= threshold -> pushed to mobile agent
    AUTO_REPLY = "AUTO_REPLY"  # P(C=1|M) < threshold -> AI draft handled auto


class TriageResult(BaseModel):
    """Response returned by ``POST /support/triage``.

    Carries the persisted ticket plus the routing decision and the raw metrics
    so n8n can branch (send SSE vs. deliver the auto-reply) without re-querying.
    """

    model_config = ConfigDict(from_attributes=True)

    decision: TriageDecision
    is_critical: bool
    criticality_score: float = Field(..., description="P(C=1|M) in [0, 1]")
    urgency_score: float = Field(..., description="U(t) at ingest time")
    threshold: float = Field(..., description="Escalation threshold in effect")
    ticket: EscalationTicket


class TicketStatus(str, Enum):
    """Lifecycle states an agent can move a ticket through."""

    PENDING = "PENDING"
    APPROVED = "APPROVED"  # agent accepted the draft as-is -> send
    MODIFIED = "MODIFIED"  # agent edited the draft -> send edited text
    DISMISSED = "DISMISSED"  # not actionable / handled elsewhere


class TicketStatusUpdate(BaseModel):
    """PATCH body for agent actions on a ticket from the mobile dashboard.

    ``status`` is required. When the agent edits the AI draft before approving,
    the new text is sent as ``ai_draft_reply`` (typically with status MODIFIED).
    """

    status: TicketStatus
    ai_draft_reply: Optional[str] = Field(
        None, description="Overridden reply text (used with MODIFIED/APPROVED)"
    )


class SSEEvent(BaseModel):
    """Envelope describing a server-sent event for documentation/typing.

    Emitted on the ``/support/stream`` channel. ``event`` names the type
    ('escalation' | 'ticket_update'); ``data`` carries the ticket payload.
    """

    event: Literal["escalation", "ticket_update"]
    data: EscalationTicket


